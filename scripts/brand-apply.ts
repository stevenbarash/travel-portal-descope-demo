import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { type BrandPalette, brand } from "@kit/brand";

/**
 * brand.ts → apps/web/src/brand/tokens.css. Run after editing the brand (`pnpm brand:apply`).
 * `--check` exits non-zero when the committed tokens.css is out of date (used by brand:guard).
 */
const OUT = resolve(import.meta.dirname, "../apps/web/src/brand/tokens.css");

const vars = (p: BrandPalette) =>
  Object.entries(p)
    .map(
      ([k, v]) =>
        `  --brand-${k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}: ${v};`,
    )
    .join("\n");

// No font @import here: tokens.css is imported after Tailwind, so a font @import would land after
// Tailwind's rules. That is invalid CSS and the browser drops it. main.tsx loads the font instead.

const css = `/* GENERATED by scripts/brand-apply.ts from packages/brand/brand.ts — do not edit. */
:root {
${vars(brand.colors.light)}
  --brand-font: "${brand.font}", ui-sans-serif, system-ui, sans-serif;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(brand.colors.dark)}
  }
}

:root[data-theme="dark"] {
${vars(brand.colors.dark)}
}
`;

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(OUT, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== css) {
    console.error(
      `brand: ${OUT} is out of date with packages/brand/brand.ts — run \`pnpm brand:apply\``,
    );
    process.exit(1);
  }
  console.log("brand: tokens.css in sync");
} else {
  writeFileSync(OUT, css);
  console.log(`brand: wrote ${OUT}`);
}
